'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const { startServer } = require('../test-support/server');

test('audio API protects configuration, runs demo, persists settings and stops cleanly', { timeout: 30000 }, async () => {
  let server = await startServer();
  try {
    assert.equal((await server.request('/api/audio/settings', { enabled: true })).status, 401);
    assert.equal((await server.request('/api/audio/state')).status, 401);
    assert.equal((await server.request('/api/audio/kick-test', {})).status, 401);
    assert.equal((await server.request('/api/kick/settings', {})).status, 401);
    await server.login();
    assert.equal((await server.request('/api/kick/settings', { color: '#ff8800', brightness: 0.7, rainbow: false }, true)).status, 200);
    let appearance = await (await server.request('/api/audio/state', undefined, true)).json();
    assert.equal(appearance.kickAppearance.color, '#ff8800');
    assert.equal(appearance.kickAppearance.brightness, 0.7);
    await server.request('/api/audio/kick-test', {}, true);
    const flash = await (await server.request('/api/state', undefined, true)).json();
    assert.equal(flash.kickFlashColor, '#ff8800');
    assert.equal(flash.kickFlashBrightness, 0.7);
    await server.request('/api/audio/settings', { kickColor: '#0088ff', kickBrightness: 0.9, sensitivity: 0.8, kickIntervalMs: 120 }, true);
    await server.request('/api/audio/kick-test', {}, true);
    const ownFlash = await (await server.request('/api/state', undefined, true)).json();
    assert.equal(ownFlash.kickFlashColor, '#0088ff');
    assert.equal(ownFlash.kickSettings.color, '#0088ff');
    assert.equal((await server.request('/api/audio/settings', { gain: 1000 }, true)).status, 400);
    assert.equal((await server.request('/api/audio/settings', { kickOpacity: 2 }, true)).status, 400);
    assert.equal((await server.request('/api/audio/settings', { kickOpacity: 0.35 }, true)).status, 200);
    assert.equal((await (await server.request('/api/audio/state', undefined, true)).json()).kickAppearance.opacity, 0.35);
    await server.request('/api/event', { type: 'kick' }, true);
    const manual = await (await server.request('/api/state', undefined, true)).json();
    assert.equal(manual.kickFlashColor, '#0088ff');
    assert.equal(manual.kickFlashOpacity, 0.35);
    const initial = await (await server.request('/api/state', undefined, true)).json();
    assert.equal(initial.audio.settings.enabled, false);
    assert.equal(initial.effects.find(effect => effect.id === 'audio_spectrum').enabled, false);
    const beforeSensitivity = initial.audio.settings.sensitivity;
    assert.equal((await server.request('/api/effects/audio_scope/config', { reactivity: 4 }, true)).status, 200);
    assert.equal((await server.request('/api/effects/audio_scope/config', { reactivity: 9 }, true)).status, 400);
    assert.equal((await (await server.request('/api/audio/state', undefined, true)).json()).settings.sensitivity, beforeSensitivity);
    assert.equal((await server.request('/api/audio/settings', { enabled: true, source: 'demo', kickEnabled: false }, true)).status, 200);
    await new Promise(resolve => setTimeout(resolve, 1500));
    const live = await (await server.request('/api/state', undefined, true)).json();
    assert.equal(live.audio.status, 'demo');
    assert.ok(live.audio.bands.some(value => value > 0));
    assert.ok(live.audio.lastBeat > 0);
    assert.ok(live.audio.beatCount > 0);
    assert.equal(live.kickFlash, false);
    assert.equal(live.audio.waveform.length, 60);
    assert.ok(live.audio.detection.threshold > 0);
    const compact = await (await server.request('/api/audio/state?visual=0', undefined, true)).json();
    assert.equal('waveform' in compact, false);
    assert.equal('bands' in compact, false);
    assert.ok(compact.beatCount > 0);
    assert.equal((await server.request('/api/effects/audio_scope/play', {}, true)).status, 200);
    assert.equal((await server.request('/api/effects/audio_mirror/play', {}, true)).status, 200);
    assert.equal((await server.request('/api/audio/settings', { kickVisual: 'shockwave', waveDurationMs: 500 }, true)).status, 200);
    await server.request('/api/audio/kick-test', {}, true);
    const layered = await (await server.request('/api/state', undefined, true)).json();
    assert.equal(layered.currentEffectId, 'audio_mirror');
    assert.equal(layered.kickFlash, false);
    assert.equal(layered.effects.some(effect => effect.id === 'shockwave'), false);
    await server.request('/api/event', { type: 'kick' }, true);
    const manualWave = await (await server.request('/api/state', undefined, true)).json();
    assert.equal(manualWave.kickFlash, false);
    assert.equal(manualWave.currentEffectId, 'audio_mirror');
    const directory = server.directory;
    await server.stop(false);
    server = await startServer(directory);
    await server.login();
    assert.equal((await (await server.request('/api/state', undefined, true)).json()).audio.settings.source, 'demo');
    assert.equal((await (await server.request('/api/state', undefined, true)).json()).effects.find(effect => effect.id === 'audio_scope').reactivity, 4);
    assert.equal((await (await server.request('/api/audio/state', undefined, true)).json()).kickAppearance.opacity, 0.35);
    assert.equal((await (await server.request('/api/state', undefined, true)).json()).audio.settings.kickVisual, 'shockwave');
    await server.request('/api/audio/settings', { enabled: false }, true);
    const stopped = await (await server.request('/api/state', undefined, true)).json();
    assert.equal(stopped.audio.status, 'disabled');
    assert.ok(stopped.audio.bands.every(value => value === 0));
    // Repeated manual pulses must not freeze playback underneath them.
    await server.request('/api/audio/settings', { kickVisual: 'flash', kickDurationMs: 300 }, true);
    const fixtures = require('./fixtures/public-gifs.json');
    const gif = await (await server.request('/api/public/gif', { gif: fixtures.disposal.base64, name: 'Under flash', clientId: 'under-flash-test-12345' })).json();
    await server.request(`/api/public-messages/${gif.id}/approve`, {}, true);
    await server.request('/api/public-messages/next', {}, true);
    for (let i = 0; i < 14; i++) {
      await server.request('/api/event', { type: 'kick' }, true);
      await new Promise(resolve => setTimeout(resolve, 100));
    }
    const underFlash = await (await server.request('/api/state', undefined, true)).json();
    assert.equal(underFlash.kickFlash, true);
    assert.equal(underFlash.publicMessages.history.find(item => item.id === gif.id).status, 'displayed');
    await server.request('/api/event', { type: 'kick', on: false }, true);
  } finally { await server.stop(); }
});
